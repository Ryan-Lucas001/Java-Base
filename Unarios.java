public class Unarios {
    public static void main(String[] args) {

        // FAZER CÓDIGOS SIMPLES PARA TER UM BOM ENTENDIMENTO 

       int a = 1;
       int b = 2;

       a++; // Para Acrementar = ++ = (a = a + 1)
       a--; // Para Decrementar = -- = (a = a - 1)

       ++b; // b = b + 1;
       --b; // b = b - 1;

       System.out.println(a);
       System.out.println(b);

       System.out.println("Mini desafio...");

        // Mistura de incremento com decremento 

       System.out.println(++a == b--);


    }
}