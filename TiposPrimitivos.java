package fundamentos;

public class TiposPrimitivos {
    public static void main(String[] args) {

        System.out.println("Tipos Pimitivos de Dados.");
        System.out.println("Apresentando 6 numéricos e 2 de palavras.");

        // INTEIROS

        //Tipo Byte --> -128 até 127.
        byte a = 3;
        System.out.println(a);
        System.out.println("Tipo Byte, representa dados de menor valor.");

        //Tipo Short 2x o armazenamento do Byte
        short b = 123;
        System.out.println(b);
        System.out.println("Tipo Short, representa dados de um valor maior ao byte.");

        //Tipo int 2x o armazenamento do Short
        int c = 12445;
        System.out.println(c);
        System.out.println("Tipo INT, representa dados de certo valor.");

        //Tipo long 2x o armazenamento do INT
        long d = 1243354353;
        System.out.println(d);
        System.out.println("Tipo LONG, representa dados de grande valor.");

        // Flutuantes

        //Tipo Float
        float r = 1;
        System.out.println(r);
        System.out.println("tipo Float, dados int e decimais.");

        //Tipo Double
        double t = 56.6788;
        System.out.println(t);
        System.out.println("tipo Double, dados para números decimais.");

        //Tipos Strings

        //tipo Char
        char e = 'a';
        System.out.println(e);
        System.out.println("Tipo Char para um espaço de string.");

        //Tipo Boolean
        boolean y = true;
        System.out.println(y);
        System.out.println("Tipo Boolean, True ou false.");

        //8 tipos de dados primitivos apresentados no java.

        System.out.println("Obrigado pela paciência, esses foram os dados do Java.");




    }

}